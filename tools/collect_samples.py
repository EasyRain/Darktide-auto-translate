"""Pick the risky shapes out of the installed mods for a sampled live test.

A full run is not practical (2000+ keys, and the free tier will not hand out a whole round), so the shapes
that have actually caused trouble are collected instead and handed to tools/sample_rounds.lua, which drives
the real pipeline against real endpoints:

  * several rich-text tags in one string (bing reordered them once);
  * a colour tag wrapping a whole string (the swatch shape, and the marquee titles);
  * line breaks, including a blank line (bing collapsed them);
  * a placeholder adjacent to a literal digit, the spot that lost a token in every round until tone=Formal;
  * styled short labels (the font-picker shape);
  * plain prose with a term in it, as a control.

Run: python tools/collect_samples.py [--per-shape N]
Writes tools/sample-input.lua (a Lua table the runner reads).
"""
import io
import json
import os
import re
import sys

MODS = r"D:\Steam\steamapps\common\Warhammer 40,000 DARKTIDE\mods"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "sample-input.lua")
OPEN, CLOSE = "\u27e6", "\u27e7"

# shapes, in the order they are reported; each is a predicate over the English source text
SHAPES = [
    ("multi-tag", lambda t: len(re.findall(r"\{#[^{}]*\}", t)) >= 3),
    ("colour-whole", lambda t: t.startswith("{#color(") and t.endswith("{#reset()}")),
    ("blank-line", lambda t: "\n\n" in t),
    ("multi-line", lambda t: t.count("\n") >= 2),
    ("digit-adjacent", lambda t: re.search(r"\{#[^{}]*\}[0-9]", t) is not None or re.search(r"[0-9]\{#[^{}]*\}", t) is not None),
    ("styled-label", lambda t: len(t) < 80 and t.startswith("{#") and t.endswith("{#reset()}")),
    ("plain-prose", lambda t: "{#" not in t and 20 <= len(t) <= 120),
]


def sources():
    """Every en string in the installed mods, with the mod it came from."""
    for base, _dirs, files in os.walk(MODS):
        if "auto_translate" in base:
            continue
        for name in files:
            if not name.endswith(".lua"):
                continue
            try:
                text = io.open(os.path.join(base, name), encoding="utf-8", errors="replace").read()
            except OSError:
                continue
            mod = os.path.relpath(base, MODS).split(os.sep)[0]
            for m in re.finditer(r'en\s*=\s*"((?:[^"\\]|\\.)*)"', text):
                try:
                    value = json.loads('"%s"' % m.group(1))
                except ValueError:
                    continue
                if value.strip():
                    yield mod, value


def main():
    per_shape = 4
    if "--per-shape" in sys.argv:
        per_shape = int(sys.argv[sys.argv.index("--per-shape") + 1])

    picked = {name: [] for name, _ in SHAPES}
    seen = set()
    for mod, value in sources():
        if value in seen:
            continue
        for name, predicate in SHAPES:
            if len(picked[name]) >= per_shape:
                continue
            if predicate(value):
                seen.add(value)
                picked[name].append({"mod": mod, "shape": name, "en": value})
                break

    rows = []
    for name, _ in SHAPES:
        for item in picked[name]:
            rows.append(item)

    lines = ["-- generated by tools/collect_samples.py", "return {"]
    for item in rows:
        lines.append("    { mod = %s, shape = %s, en = %s }," % (
            json.dumps(item["mod"], ensure_ascii=False),
            json.dumps(item["shape"], ensure_ascii=False),
            json.dumps(item["en"], ensure_ascii=False)))
    lines.append("}")
    io.open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")

    print("  %d sample(s) -> %s" % (len(rows), os.path.basename(OUT)))
    for name, _ in SHAPES:
        got = len(picked[name])
        print("    %-16s %d" % (name, got))
        for item in picked[name][:2]:
            print("        %s" % item["en"][:96].replace("\n", " / "))


main()
