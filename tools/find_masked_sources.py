"""Find the source text of the refused keys in the mods' own localisation files.

The masked text has to be produced by the real glossary (tools/masked_strings.lua), but the *source*
lookup cannot use io.popen here - pipes are blocked in this sandbox - so it is done in Python and
handed over as a Lua table. Non-ASCII stays literal (ensure_ascii=False) because Lua 5.1 has no \\u
escapes.
"""
import io
import json
import os
import re

MODS = r"D:\Steam\steamapps\common\Warhammer 40,000 DARKTIDE\mods"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "masked-input.lua")

WANT = [
    ("Alfs_DMF_Extensions", "keybind_reset_tab_tooltip"),
    ("Alfs_DMF_Extensions", "enable_RGB_widget_tooltip"),
    ("AutoMark", "companion_distance_threshold_tooltip"),
    ("AutoMark", "companion_mark_max_distance_tooltip"),
    ("AutoMark", "companion_range_limitation_tooltip"),
    ("AutoMark", "companion_cancel_mark_breed_distance_threshold_description"),
    ("AutoMark", "servo_skull_lose_sight_tolerance_tooltip"),
    ("AutoMark", "servo_skull_mark_keybind_description"),
]


def from_store(mod, key):
    """The store's `en` is the exact text the online path sends: it carries the {#color(..)} wrapper the
    mod adds at runtime, which the localisation file does not have."""
    path = os.path.join(MODS, "auto_translate", "translations", "ja", mod + ".lua")
    if not os.path.exists(path):
        return None
    text = io.open(path, encoding="utf-8", errors="replace").read()
    m = re.search(r'\["%s"\] = \{(.*?)\n\s*\},' % re.escape(key), text, re.S)
    if not m:
        return None
    en = re.search(r'en = "((?:[^"\\]|\\.)*)"', m.group(1))
    return json.loads('"%s"' % en.group(1)) if en else None


def lua_string(value):
    """A double-quoted Lua string literal for value."""
    return json.dumps(value, ensure_ascii=False)


def find(mod, key):
    root = os.path.join(MODS, mod)
    for base, _dirs, files in os.walk(root):
        for name in files:
            if not name.endswith(".lua") or "localization" not in name.lower():
                continue
            text = io.open(os.path.join(base, name), encoding="utf-8", errors="replace").read()
            # key = { ... en = "..." ... } - a non-greedy block up to the closing brace at line start
            for m in re.finditer(r"(?:^|\n)\s*%s\s*=\s*\{(.*?)\n\s*\}" % re.escape(key), text, re.S):
                en = re.search(r'en\s*=\s*"((?:[^"\\]|\\.)*)"', m.group(1))
                if en:
                    return json.loads('"%s"' % en.group(1))
    return None


lines = ["-- generated by tools/find_masked_sources.py", "return {"]
found = 0
for mod, key in WANT:
    en = from_store(mod, key) or find(mod, key)
    if en is None:
        print("  %s:%s -> source not found" % (mod, key))
        continue
    found += 1
    lines.append("    { mod = %s, key = %s, en = %s }," % (lua_string(mod), lua_string(key), lua_string(en)))
    print("  %s:%s -> %d bytes" % (mod, key, len(en)))
lines.append("}")

io.open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
print("  %d source(s) -> %s" % (found, OUT))
